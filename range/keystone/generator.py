# Brain-hosted service-host VMs from the 2026-10-15 redesign. Not modules —
# they are the podman runtimes the dmz pods ride macvlan on. Shown on the
# dashboard so the dmz column reflects the real estate: each pod hangs off
# the VM that hosts it. Keyed by hostname; membership is derived from each
# module manifest's ``evidence.host``.
SERVICE_HOST_VMS: Dict[str, Dict] = {
    "dmz-web-a":  {"vmid": 970, "real_ip": "10.99.50.101"},
    "dmz-web-b":  {"vmid": 971, "real_ip": "10.99.50.102"},
    "dmz-svc":    {"vmid": 972, "real_ip": "10.99.50.103"},
    "dmz-runner": {"vmid": 973, "real_ip": "10.99.50.104"},
}


def _service_host_of(man: Manifest) -> str:
    """The service-host VM a container module runs on, from evidence.host.

    Manifests stamp ``host: brain dmz-web-a (VM 970)``; returns the bare
    hostname ("" when the module isn't on a service host).
    """
    host = str((man.evidence or {}).get("host") or "")
    for name in SERVICE_HOST_VMS:
        if name in host:
            return name
    return ""


def _yaml_scalar(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    if s == "" or any(c in s for c in ":#{}[]") or s != s.strip():
        return json.dumps(s)
    return s


def build_networks(assignments: List[Assignment]) -> Dict:
    nets = {}
    for zone, cidr in zones.ZONE_SUBNETS.items():
        gw = str(__import__("ipaddress").ip_network(cidr).network_address + 1)
        nets[zone] = {
            "name": f"keystone-{zone}",
            "subnet": cidr,
            "gateway": gw,
            "internal": zone != "attacker",  # only the attacker net may egress
            "interface": f"ks-{zone}",
            "routes": [{"destination": "10.80.0.0/16", "gateway": gw}],
        }
    commands = [
        f"podman network create --subnet {n['subnet']} --gateway {n['gateway']}"
        + f" --interface-name {n['interface']} --route 10.80.0.0/16,{n['gateway']}"
        + (" --internal" if n["internal"] else "")
        + f" {n['name']}"
        for n in nets.values()
    ]
    return {"networks": nets, "create_commands": commands}


def build_compose(container_mods: List[Manifest], assignments: Dict[str, Assignment]) -> str:
    lines = ["# Generated by keystone.generator — do not edit by hand.",
             "# Rootless podman:  podman-compose -f build/compose.yaml up -d",
             "networks:"]
    for zone, cidr in zones.ZONE_SUBNETS.items():
        lines += [f"  keystone-{zone}:", "    external: true",
                  f"    name: keystone-{zone}"]
    lines.append("services:")
    # attacker/operator box
    lines += [
        "  attacker:",
        "    image: localhost/keystone/attacker:latest",
        "    build:",
        f"      context: {json.dumps(os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'infra', 'attacker')))}",
        "      dockerfile: Containerfile",
        "    container_name: keystone-attacker",
        "    cap_drop: [NET_RAW]",
        "    hostname: attacker",
        "    command: [\"sleep\", \"infinity\"]",
        "    networks:",
        "      keystone-attacker:",
        f"        ipv4_address: {zones.ATTACKER_IP}",
    ]
    for man in container_mods:
        a = assignments[man.id]
        lines += [
            f"  {man.id}:",
            f"    image: localhost/keystone/{man.id}:latest",
            f"    build:",
            f"      context: {json.dumps(os.path.abspath(man.path))}",
            f"      dockerfile: {man.build.containerfile}",
            f"    container_name: keystone-{man.id}",
            "    cap_drop: [NET_RAW]",
            f"    hostname: {man.hostname}",
            "    networks:",
            f"      keystone-{man.network_zone}:",
            f"        ipv4_address: {a.ip}",
        ]
        runtime_file = os.path.join(man.path, "runtime.json")
        ready = False
        if os.path.isfile(runtime_file):
            with open(runtime_file, encoding="utf-8") as fh:
                ready = json.load(fh).get("ready") is True
        if not ready:
            lines.append('    profiles: ["needs-app"]')
        if man.ports:
            lines.append("    expose:")
            for p in man.ports:
                lines.append(f"      - \"{p}\"")
    return "\n".join(lines) + "\n"


def build_firewall(assignments: List[Assignment]) -> str:
    rules = firewall_rules(assignments)
    out = [
        "#!/usr/sbin/nft -f",
        "# Generated by keystone.generator. Default DROP; only zone-policy allows exist.",
        "# Enforces: attacker->dmz, dmz->corp, corp->data. No attacker/dmz->data.",
        "# Replace only our table, atomically; preserve Podman and host rules.",
        "add table inet keystone",
        "delete table inet keystone",
        "table inet keystone {",
        "  chain input {",
        "    type filter hook input priority -10; policy accept;",
        "    ct state established,related accept",
        "    ip saddr { 10.80.0.0/24, 10.80.10.0/24, 10.80.20.0/24, 10.80.30.0/24 } drop",
        "  }",
        "  chain forward {",
        "    type filter hook forward priority -10; policy drop;",
        "    # Do not change forwarding for unrelated host/container networks.",
        "    meta nfproto ipv6 iifname != { \"ks-attacker\", \"ks-dmz\", \"ks-corp\", \"ks-data\" } oifname != { \"ks-attacker\", \"ks-dmz\", \"ks-corp\", \"ks-data\" } accept",
        "    ip saddr != { 10.80.0.0/24, 10.80.10.0/24, 10.80.20.0/24, 10.80.30.0/24 } ip daddr != { 10.80.0.0/24, 10.80.10.0/24, 10.80.20.0/24, 10.80.30.0/24 } accept",
        "    ct state established,related accept",
    ]
    for zone, cidr in zones.ZONE_SUBNETS.items():
        out.append(f"    # intra-zone {zone}")
        out.append(f"    ip saddr {cidr} ip daddr {cidr} accept")
    for r in rules:
        out.append(
            f"    ip saddr {r['src_cidr']} ip daddr {r['dst_cidr']} accept  "
            f"# {r['src_zone']}->{r['dst_zone']}"
        )
    out += ["    # everything else (incl. attacker->data, dmz->data) is dropped",
            "  }", "}", ""]
    return "\n".join(out)


def build_vms(vm_mods: List[Manifest], assignments: Dict[str, Assignment]) -> Dict:
    vms = []
    for man in vm_mods:
        a = assignments[man.id]
        runtime = {}
        runtime_file = os.path.join(man.path, "runtime.json")
        if os.path.isfile(runtime_file):
            with open(runtime_file, encoding="utf-8") as fh:
                runtime = json.load(fh)
        vms.append({
            "id": man.id,
            "hostname": man.hostname,
            "zone": man.network_zone,
            "ip": a.ip,
            "ports": list(man.ports),
            "vm_spec": os.path.join("modules", os.path.basename(man.path), man.build.vm_spec),
            "technique_class": man.technique_class,
            "vulnerability": man.vulnerability,
            "ready": runtime.get("ready") is True,
            "baseline_snapshot": runtime.get("baseline_snapshot", "clean"),
            "health": runtime.get("health", ""),
            "bringup": [
                f"# define & start {man.hostname} on bridge keystone-{man.network_zone}",
                f"virsh define modules/{os.path.basename(man.path)}/{man.build.vm_spec}",
                f"virsh start {man.hostname}",
            ],
        })
    return {"vms": vms}


def build_infra(manifests: List[Manifest], assignments: Dict[str, Assignment]) -> Dict:
    """Bring-up list for non-podman, non-libvirt modules.

    Covers the substrates introduced by the hybrid expansion:
      - ``lxc``       CORP/DATA hosts provisioned as dedicated LXCs on the
                       brain (Proxmox, reserved VMID range 950-969)
      - ``physical``  the planted dropbox (Raspberry Pi), dual-homed
      - ``remote-vm`` a VM on the brain's Proxmox that is REUSED rather than
                       built (dc01 / VMID 930) — distinct from a Parrot-local
                       libvirt ``vm``, which goes through build_vms() instead.
    These deliberately do NOT go into compose.yaml (podman) or vms.json
    (libvirt); the brain-side and physical bring-up consume this artifact.
    ``real_ip``/``vmid`` come from the manifest's free-form ``evidence``
    block when present — the logical ``ip`` stays the synthetic, deterministic
    zone address used for scoring/dashboard consistency across all hosts,
    real or virtual.
    """
    notes = {
        "lxc": "brain LXC (Proxmox, VMID 950-969) — provisioned on lab-brain (willshomelab, 192.168.0.240)",
        "physical": "physical lab target on approved hardware; network and reset details are module-specific",
        "remote-vm": "reused VM on the brain's Proxmox (qm) — started/integrated, never wiped/reprovisioned",
    }
    items = []
    for man in sorted(manifests, key=lambda m: m.id):
        if man.substrate not in ("lxc", "physical", "remote-vm"):
            continue
        a = assignments[man.id]
        items.append({
            "id": man.id,
            "hostname": man.hostname,
            "substrate": man.substrate,
            "zone": man.network_zone,
            "ip": a.ip,
            "real_ip": (man.evidence or {}).get("ip"),
            "vmid": (man.evidence or {}).get("vmid"),
            "ports": list(man.ports),
            "technique_class": man.technique_class,
            "vulnerability": man.vulnerability,
            "note": notes[man.substrate],
        })
    return {"infra": items}


def build_topology(manifests: List[Manifest], assignments: Dict[str, Assignment]) -> Dict:
    nodes = [{
        "id": "attacker", "label": "operator", "type": "attacker",
        "zone": "attacker", "position": [0, 0], "ip": zones.ATTACKER_IP,
    }]
    # lay nodes out in columns by zone
    col = {"attacker": 0, "dmz": 1, "corp": 2, "data": 3}
    row = {z: 0 for z in col}
    for man in sorted(manifests, key=lambda m: (m.network_zone, m.id)):
        a = assignments[man.id]
        z = man.network_zone
        nodes.append({
            "id": man.id,
            "label": man.hostname,
            "type": man.substrate,
            "zone": z,
            "ip": a.ip,
            "real_ip": (man.evidence or {}).get("ip"),
            "position": [col[z] * 240, row[z] * 120 + 120],
            "technique_class": man.technique_class,
            "cves": list(man.vulnerability.get("cves", [])),
        })
        row[z] += 1
    # Service-host VMs ride at the bottom of the dmz column, wired to the
    # pods they host so the physical layout is visible on the dashboard.
    for name, spec in sorted(SERVICE_HOST_VMS.items()):
        nodes.append({
            "id": name,
            "label": f"{name} (VM {spec['vmid']})",
            "type": "vm",
            "zone": "dmz",
            "ip": "",
            "real_ip": f"{spec['real_ip']} (service-host VM on brain vmbr9)",
            "position": [col["dmz"] * 240, row["dmz"] * 120 + 120],
            "technique_class": "service-host",
            "cves": [],
        })
        row["dmz"] += 1
    edges = []
    for man in manifests:
        for en in man.enables:
            edges.append({"src": man.id, "dst": en, "kind": "trust", "state": "unknown"})
    # Pods hang off their service-host VM (drawn dashed until a run uses them).
    for man in manifests:
        host = _service_host_of(man)
        if host:
            edges.append({"src": host, "dst": man.id, "kind": "hosts", "state": "unknown"})
    # network edges follow the zone policy, drawn attacker->dmz->corp->data
    for src, dsts in zones.ZONE_POLICY.items():
        for dst in dsts:
            if src != dst:
                edges.append({"src": src, "dst": dst, "kind": "network", "state": "unknown"})
    # The planted dropbox is a SECOND, parallel initial-access edge: the
    # operator's C2 (Tailscale) reaches it directly, bypassing the DMZ. This
    # is a real exception drawn explicitly (not a zone-policy edge) because
    # drop01 sits in the corp zone/column but is reachable like an entry
    # vector — exactly the "parallel beachhead" the engagement narrative
    # requires. No equivalent edge exists into data: the crown is still only
    # reachable via corp->data, same as every other path.
    for man in manifests:
        if man.substrate == "physical" and man.is_initial_access:
            edges.append({"src": "attacker", "dst": man.id, "kind": "network", "state": "unknown",
                          "label": "C2 (planted implant)"})
    segments = [
        {"id": "attacker", "label": "ATTACK", "vlan": 66,
         "cidr": zones.LAB_ZONE_SUBNETS["attacker"], "ports": "SG108E p2, p6"},
        {"id": "dmz", "label": "DMZ", "vlan": 9,
         "cidr": zones.LAB_ZONE_SUBNETS["dmz"], "ports": "SG108E p4 / brain vmbr9"},
        {"id": "corp", "label": "CORP", "vlan": 50,
         "cidr": zones.LAB_ZONE_SUBNETS["corp"], "ports": "SG108E p3 / brain vmbr50"},
        {"id": "data", "label": "DATA", "vlan": 51,
         "cidr": zones.LAB_ZONE_SUBNETS["data"], "ports": "SG108E p7 / brain vmbr51"},
    ]
    fabric = {
        "devices": [
            {"id": "hex", "label": "MikroTik hEX", "role": "segmentation firewall",
             "address": "10.10.0.1", "detail": "default-deny nftables · inter-VLAN routing"},
            {"id": "sg108e", "label": "TP-Link SG108E", "role": "managed switch",
             "address": "10.10.0.5", "detail": "p1 trunk · 802.1Q access segmentation"},
            {"id": "brain", "label": "lab-brain", "role": "Proxmox compute",
             "address": "192.168.0.240", "detail": "lan2 trunk · vmbr9/50/51"},
            {"id": "evilkit", "label": "EvilKit OS Pi", "role": "physical mesh worker",
             "address": "10.50.0.220", "detail": "SG108E p3 · CORP only"},
        ],
        "links": [
            {"src": "hex", "dst": "sg108e", "label": "lan5 ↔ p1 · VLAN 9/50/51/66"},
            {"src": "hex", "dst": "brain", "label": "lan2 ↔ Proxmox · VLAN 9/50/51"},
            {"src": "sg108e", "dst": "evilkit", "label": "p3 access · VLAN 50"},
        ],
        "management": "VLAN 1 · SG108E p5/p8 · hEX dedicated lan3 management path",
    }
    return {
        "nodes": nodes,
        "edges": edges,
        "zones": list(zones.ZONE_SUBNETS.keys()),
        "segments": segments,
        "fabric": fabric,
    }


def build_scoring_key_template(manifests: List[Manifest],
                               assignments: Dict[str, Assignment]) -> Dict:
    hosts = []
    for man in sorted(manifests, key=lambda m: m.id):
        a = assignments[man.id]
        hosts.append({"id": man.id, "hostname": man.hostname, "ip": a.ip, "zone": man.network_zone})
    return {
        "seed": "<FILLED-BY-reset.sh>",
        "canary": "<FILLED-BY-reset.sh>",
        "crown_flags": [],
        "in_scope_cidrs": zones.all_in_scope_cidrs(),
        "hosts": hosts,
    }


def build_reachability_doc(manifests: List[Manifest],
                           assignments: Dict[str, Assignment]) -> str:
    lines = ["# Reachability map (generated)", "",
             "## Zone policy (source -> reachable destinations)", ""]
    for src, dsts in zones.ZONE_POLICY.items():
        lines.append(f"- **{src}** -> {', '.join(dsts)}")
    lines += ["", "> DATA is absent from attacker/dmz reachability: the crown jewel "
              "can only be reached by pivoting attacker -> dmz -> corp -> data.", "",
              "## Hosts", "", "| module | host | zone | ip | ports | class | CVE(s) | role |",
              "|---|---|---|---|---|---|---|---|"]
    for man in sorted(manifests, key=lambda m: (m.network_zone, m.id)):
        a = assignments[man.id]
        role = "initial-access" if man.is_initial_access else "escalation/lateral"
        ports = ",".join(str(p) for p in man.ports) or "-"
        cves = ",".join(str(c) for c in man.vulnerability.get("cves", [])) or "-"
        lines.append(f"| {man.id} | {man.hostname} | {man.network_zone} | {a.ip} "
                     f"| {ports} | {man.technique_class} | {cves} | {role} |")
    # The crown end-game matrix: one vault credential per deep branch, so the
    # range completes ~10 genuinely different ways. Every token below is
    # accepted by vault-keystone; recovering any one (always post-exploit,
    # from a root/DA/SYSTEM-only location) opens the crown.
    branches = [m for m in manifests if m.vault_token]
    lines += ["", "## Crown unlock matrix (one accepted credential per branch)", "",
              "The DATA-tier vault accepts every credential below. Recovering any one",
              "completes the range; no branch is a required stage of any other.", "",
              "| module (branch) | technique class | credential lives at | recovery condition |",
              "|---|---|---|---|"]
    for man in sorted(branches, key=lambda m: m.id):
        tok = man.vault_token
        note = tok.get("note") or "post-exploitation"
        lines.append(f"| {man.id} | {man.technique_class} | "
                     f"`{tok['placement']}` | {note} |")
    lines.append(f"| vault-keystone | crown-store | accepted set = the "
                 f"{len(branches)} tokens above | presents X-Vault-Token on GET "
                 f"/secrets/master.key |")
    return "\n".join(lines) + "\n"


def generate(modules_dir: str, out_dir: str) -> Dict[str, str]:
    manifests = discover_modules(modules_dir)
    assignment_list = assign_ips(manifests)
    assignments = {a.module_id: a for a in assignment_list}

    container_mods = [m for m in manifests if m.substrate == "container"]
    vm_mods = [m for m in manifests if m.substrate == "vm"]

    os.makedirs(out_dir, exist_ok=True)
    written: Dict[str, str] = {}

    def _dump(name: str, content):
        path = os.path.join(out_dir, name)
        with open(path, "w", encoding="utf-8") as fh:
            if isinstance(content, str):
                fh.write(content)
            else:
                json.dump(content, fh, indent=2)
        written[name] = path

    lxc_guests = lxc.lxc_guests(manifests)

    _dump("networks.json", build_networks(assignment_list))
    _dump("compose.yaml", build_compose(container_mods, assignments))
    _dump("firewall.nft", build_firewall(assignment_list))
    # The brain (Proxmox) CORP/DATA LXC tier: a provisioning plan and a
    # brain-side segmentation ruleset, the LXC analogues of compose.yaml and
    # firewall.nft. Both are pure string/dict construction (no pct/nft needed).
    _dump("lxc.json", lxc.build_lxc(manifests))
    _dump("brain-firewall.nft", lxc.render_brain_firewall(lxc_guests))
    # The hEX (OpenWrt labrouter) re-homed enforcement: the same zone policy
    # expressed for the brain<->hEX VLAN trunk, emitted as a fw4-includable
    # chain (/etc/nftables.d/keystone-hex.nft). The brain ruleset above is a
    # separate, unchanged output target.
    _dump("hex-firewall.nft", hexfirewall.render_hex_firewall(lxc_guests))
    _dump("vms.json", build_vms(vm_mods, assignments))
    _dump("infra.json", build_infra(manifests, assignments))
    _dump("topology.json", build_topology(manifests, assignments))
    _dump("scoring_key.template.json", build_scoring_key_template(manifests, assignments))
    _dump("reachability.md", build_reachability_doc(manifests, assignments))

    summary = {
        "modules": len(manifests),
        "containers": len(container_mods),
        "vms": len(vm_mods),
        "lxc": len([m for m in manifests if m.substrate == "lxc"]),
        "physical": len([m for m in manifests if m.substrate == "physical"]),
        "remote_vm": len([m for m in manifests if m.substrate == "remote-vm"]),
        "initial_access_vectors": sorted(m.technique_class for m in manifests if m.is_initial_access),
        "crown_isolated": zones.crown_is_isolated(manifests),
        # Real-layer check for the brain tier: every source the brain firewall
        # lets reach a DATA host must be a CORP address (never dmz/attacker).
        "brain_crown_sources": lxc.crown_reachable_sources(lxc_guests),
    }
    _dump("summary.json", summary)
    return written


def main(argv=None) -> int:
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser(description="Keystone range generator")
    ap.add_argument("--modules", default=os.path.join(here, "modules"))
    ap.add_argument("--out", default=os.path.join(here, "build"))
    args = ap.parse_args(argv)
    written = generate(args.modules, args.out)
    print(f"Generated {len(written)} artifacts into {args.out}:")
    for name, path in written.items():
        print(f"  {name:<28} {path}")
    with open(os.path.join(args.out, "summary.json"), encoding="utf-8") as fh:
        summary = json.load(fh)
    print("\nSummary:")
    print(json.dumps(summary, indent=2))
    if not summary["crown_isolated"]:
        print("\nWARNING: crown jewel is NOT isolated — check ZONE_POLICY!")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
