#!/usr/bin/env python3
"""Generator — turn the set of module manifests into a runnable range plan.

Reads EVERY ``modules/<name>/manifest.yaml`` and emits, into ``build/``:

  networks.json        podman network specs (one per zone) + create commands
  compose.yaml         a compose file (rootless podman / podman-compose) for the
                       container modules + the attacker box
  firewall.nft         an nftables ruleset enforcing the zone reachability map
  vms.json             bring-up list for the VM modules (virsh / vmrun)
  topology.json        dashboard seed topology (states all "unknown")
  scoring_key.template.json   host->ip->zone map; reset.sh fills seed/canary/crown
  reachability.md      human-readable zone matrix + per-module port table

Everything here is pure string/dict construction: it does NOT require podman or
libvirt to be present, so it runs (and is unit-tested) on a build box. The
bring-up scripts consume these artifacts on the real Parrot host.
"""
from __future__ import annotations

import argparse
